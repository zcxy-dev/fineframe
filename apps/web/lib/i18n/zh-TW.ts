/** A date and time as Taiwan writes them: 2026/10/19 下午 1:47. */
function date(milliseconds: number): string {
  return new Date(milliseconds)
    .toLocaleString("zh-TW", {
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
      hour: "numeric",
      minute: "2-digit",
    })
    .replace(/\s+/g, " ")
    .replace(/([^\d ])(\d{1,2}:\d{2})$/, "$1 $2");
}

